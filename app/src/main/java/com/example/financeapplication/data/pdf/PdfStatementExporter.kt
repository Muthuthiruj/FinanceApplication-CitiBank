package com.example.financeapplication.data.pdf

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.example.financeapplication.core.Formatters
import com.example.financeapplication.domain.model.StatementData
import com.example.financeapplication.domain.repository.StatementExporter
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream
import javax.inject.Inject

class PdfStatementExporter @Inject constructor(
    @ApplicationContext private val context: Context
) : StatementExporter {

    override suspend fun export(data: StatementData): File = withContext(Dispatchers.IO) {
        val dir = File(context.cacheDir, "statements").apply { mkdirs() }
        val s = data.statement
        val file = File(dir, "statement_${s.accountName.replace(' ', '_')}_${s.year}_${s.month + 1}.pdf")

        val doc = PdfDocument()
        val w = 595
        val h = 842
        val margin = 40f
        val navy = Color.parseColor("#0B2A6B")

        val title = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.WHITE; textSize = 20f; typeface = Typeface.DEFAULT_BOLD }
        val bold = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.BLACK; textSize = 11f; typeface = Typeface.DEFAULT_BOLD }
        val text = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.DKGRAY; textSize = 11f }
        val right = Paint(text).apply { textAlign = Paint.Align.RIGHT }
        val rightBold = Paint(bold).apply { textAlign = Paint.Align.RIGHT }
        val band = Paint().apply { color = navy }
        val line = Paint().apply { color = Color.LTGRAY; strokeWidth = 0.8f }

        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create())
        var c = page.canvas
        var y: Float

        fun header(): Float {
            c.drawRect(0f, 0f, w.toFloat(), 90f, band)
            c.drawText("CitiBank", margin, 42f, title)
            c.drawText("Account statement – ${Formatters.monthYear(s.year, s.month)}", margin, 66f, Paint(title).apply { textSize = 12f; typeface = Typeface.DEFAULT })
            return 120f
        }
        y = header()

        c.drawText(data.account.name, margin, y, bold); y += 16f
        c.drawText("Account ${data.account.masked}", margin, y, text); y += 24f
        c.drawText("Opening balance", margin, y, text); c.drawText(Formatters.money(data.openingBalance), w - margin, y, right); y += 16f
        c.drawText("Closing balance", margin, y, bold); c.drawText(Formatters.money(data.closingBalance), w - margin, y, rightBold); y += 28f

        c.drawText("Date", margin, y, bold); c.drawText("Description", margin + 80f, y, bold); c.drawText("Amount", w - margin, y, rightBold)
        y += 6f; c.drawLine(margin, y, w - margin, y, line); y += 16f

        if (data.transactions.isEmpty()) {
            c.drawText("No transactions in this period.", margin, y, text)
        }
        for (t in data.transactions) {
            if (y > h - 60f) {
                doc.finishPage(page)
                pageNo += 1
                page = doc.startPage(PdfDocument.PageInfo.Builder(w, h, pageNo).create())
                c = page.canvas
                y = header()
            }
            c.drawText(Formatters.shortDate(t.timestamp), margin, y, text)
            c.drawText(t.title.take(48), margin + 80f, y, text)
            c.drawText(Formatters.signedMoney(t.amount), w - margin, y, right)
            y += 18f
        }
        c.drawText("Generated by CitiBank demo app – not a legal document.", margin, h - 30f, Paint(text).apply { textSize = 9f })
        doc.finishPage(page)
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        file
    }
}
